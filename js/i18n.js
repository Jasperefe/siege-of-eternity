export function setLang(code) { lang = RU_LANGS.has(code) ? 'ru' : 'en'; document.documentElement.lang = lang; }
export function getLang() { return lang; }
const RU_LANGS = new Set(['ru', 'be', 'kk', 'uk', 'uz']);

export function t(s, p) {
  if (s == null) return '';
  let out = lang === 'ru' ? (RU[s] ?? s) : s;
  if (p) for (const k in p) out = out.split('{' + k + '}').join(p[k]);
  return out;
}

